BASE_ALIASES = ['diamond алмаз бриллиант','ruby рубин','emerald изумруд','sapphire сапфир','amethyst аметист','topaz топаз','turquoise бирюза','jasper яшма','agate агат','aquamarine аквамарин','onyx оникс','citrine цитрин']

def write():
    # The historical first twelve IDs and their educational values stay exact.
    original = json.loads((ROOT/'shared/catalog/catalog_base12.json').read_text(encoding='utf-8'))
    rows = [dict(row) for row in original[:12]]
    for sid,name,english,russian,carats,price,transparency,color in EXTRA:
        rows.append(dict(id=sid,name=name,category='Асыл тас' if sid==24 else 'Жартылай асыл тас',carats=carats,
            price_per_carat=price,cost=format(Decimal(carats)*Decimal(price),'.2f'),transparency=transparency,
            color=color,photo=f'/assets/stone_{sid}.jpg',aliases=f'{english} {russian}'))
    for index,row in enumerate(rows):
        row.setdefault('aliases',BASE_ALIASES[index] if index<12 else '')
        row['description']=DESCRIPTIONS[row['id']]
        row['care']='Соққыдан және тұрмыстық химиядан қорғаңыз. Бөлек жұмсақ қапта сақтаңыз.'
        row['educational']=True
    assert len(rows)==48 and len({r['id'] for r in rows})==48 and len({r['color'] for r in rows})==48
    data=json.dumps(rows,ensure_ascii=False,indent=2)+'\n'
    for file in ['shared/catalog/catalog_v4.json','android/app/src/main/assets/catalog_v4.json','site_online/public/assets/catalog.json']:
        path=ROOT/file;path.parent.mkdir(parents=True,exist_ok=True);path.write_text(data,encoding='utf-8')
    (ROOT/'site_online/worker/catalog.js').write_text('// Educational catalog; generated by tools/catalog_v4_data.py.\nexport default '+data.strip()+';\n',encoding='utf-8')
    java='package kz.asyltas.model;\n\nimport java.util.*;\n\n/** Баға, салмақ және мөлдірлік — оқу деректері. Алғашқы 12 ID өзгермейді. */\npublic final class Catalog {\n  private static final List<Stone> STONES = Collections.unmodifiableList(Arrays.asList(\n'
    for index,row in enumerate(rows):
        cls='PreciousStone' if row['category']=='Асыл тас' else 'SemiPreciousStone'
        java+=f'      new {cls}({row["id"]}, "{row["name"]}", "{row["carats"]}", "{row["price_per_carat"]}", {row["transparency"]}, "{row["color"]}")'+(',' if index<len(rows)-1 else '')+'\n'
    java+='  ));\n\n  private Catalog() {}\n  public static List<Stone> all() { return STONES; }\n  public static Stone get(int id) {\n    for (Stone stone : STONES) if (stone.getId() == id) return stone;\n    throw new IllegalArgumentException("Каталогта мұндай тас жоқ.");\n  }\n}\n'
    (ROOT/'shared/src/kz/asyltas/model/Catalog.java').write_text(java,encoding='utf-8')
    print(f'Generated {len(rows)} catalog records; preserved IDs 1–12.')

if __name__=='__main__':write()
